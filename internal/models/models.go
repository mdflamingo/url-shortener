// Package models определяет структуры данных для API URL Shortener
//
// Пакет содержит модели запросов и ответов, используемые в HTTP API:
//   - Создание одиночных коротких ссылок (текстовый и JSON форматы)
//   - Пакетное создание коротких ссылок
//   - Получение списка ссылок пользователя
//
// Все модели сериализуются в/из JSON и используются обработчиками в пакете handler.
package models

// Request представляет тело JSON-запроса для создания одной короткой ссылки
// Используется в эндпоинте POST /api/shorten для создания короткой ссылки
// из переданного URL в формате JSON.
type Request struct {
	URL string `json:"url"` // Исходный URL для сокращения (не должен быть пустым)
}

// Response представляет тело JSON-ответа при создании короткой ссылки
// Возвращается в ответ на успешный запрос создания короткой ссылки.
// Содержит полный сокращенный URL (базовый URL + короткий идентификатор).
type Response struct {
	Result string `json:"result"` // Полный сокращенный URL (включая базовый домен)
}

// BatchRequest представляет элемент запроса для пакетного создания ссылок
// Используется в эндпоинте POST /api/shorten/batch для массового создания
// нескольких коротких ссылок в одном запросе.
// Особенности:
//   - Каждый элемент содержит уникальный correlation_id для сопоставления запросов и ответов
//   - Позволяет клиенту отслеживать соответствие между исходными и сокращенными URL
//   - Correlation ID генерируется клиентом и не должен гарантировать уникальность на сервере
type BatchRequest struct {
	CorrelationID string `json:"correlation_id"` // Клиентский идентификатор для маппинга ответов
	OriginalURL   string `json:"original_url"`   // Исходный URL для сокращения
}

// BatchResponse представляет элемент ответа при пакетном создании ссылок
// Возвращается в ответ на пакетный запрос создания коротких ссылок.
// Содержит соответствие между correlation_id из запроса и полученным коротким URL.
// Особенности:
//   - Порядок элементов в ответе может не соответствовать порядку в запросе
//   - Клиент должен использовать correlation_id для сопоставления
//   - Каждый элемент ответа гарантированно соответствует одному элементу запроса
type BatchResponse struct {
	CorrelationID string `json:"correlation_id"` // Идентификатор из запроса для связывания
	ShortURL      string `json:"short_url"`      // Полный сокращенный URL
}

// ResponseByUser представляет элемент ответа при запросе всех URL пользователя
// Используется в эндпоинте GET /api/user/urls для получения списка всех
// сокращенных URL, созданных текущим пользователем.
// Особенности:
//   - Возвращает только URL, принадлежащие аутентифицированному пользователю
//   - Включает как исходные, так и сокращенные версии URL
//   - Не включает удаленные URL (помеченные как deleted)
type ResponseByUser struct {
	OriginalURL string `json:"original_url"` // Исходный длинный URL
	ShortURL    string `json:"short_url"`    // Полный сокращенный URL
}

// ResponseStats представляет элемент ответа при запросе на количество url и пользователей в сервисе
// Используется в эндпоинте GET /api/internal/stats
type ResponseStats struct {
	Urls  int `json:"urls"`  // количество сокращенных url
	Users int `json:"users"` // количество пользователей в системе
}
